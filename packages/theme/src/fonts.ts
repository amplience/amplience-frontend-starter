// Brand font definitions for @amplience/frontend-starter-theme.
//
// Each font is exposed as a CSS variable (--nf-*) so tokens.css can reference
// it under [data-brand] selectors without coupling to next/font internals.
// The consuming app applies .variable classNames to <html> so every selector
// in the document has access to all --nf-* properties.
//
// Fonts are self-hosted from ../fonts (Latin subset .woff2 files taken from
// Fontsource, each family with its own licence file). We deliberately do NOT
// use next/font/google: it downloads every family from Google at build time,
// and a single failed or rate-limited request fails the whole build with
// "Can't resolve '@vercel/turbopack-next/internal/font/google/font'".
// Self-hosting makes the build fully offline for fonts and pins the versions.
// See packages/theme/README.md#fonts for licensing and how to add or refresh
// a font.
//
// Variable fonts are used wherever the family has one — one file covers the
// whole weight axis. Lato and Poppins have no variable cut, so they ship one
// static file per weight.
//
// next/font/local requires literal (statically analysable) arguments, so each
// call is written out in full rather than generated by a helper.

