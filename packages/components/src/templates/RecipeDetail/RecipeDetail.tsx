import type { ContentMediaData, MediaLoadPriority } from '@amplience/frontend-starter-types'

import { Container } from '../../atoms/Container/Container'
import { List } from '../../atoms/List/List'
import { ListItem } from '../../atoms/ListItem/ListItem'
import { Typography } from '../../atoms/Typography/Typography'
import type { Attribute } from '../../molecules/AttributeList/AttributeList'
import { Markdown } from '../../molecules/Markdown/Markdown'
import { HeroBlock } from '../../organisms/HeroBlock/HeroBlock'
import styles from './RecipeDetail.module.css'

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type RecipeIngredient = {
  /** Catalogue product code. Blank/absent for ingredients with no product. */
  readonly productCode?: string
  readonly name: string
  /** e.g. "280g" */
  readonly quantity?: string
  /** e.g. "1 x Each" */
  readonly portion?: string
}

/** Nutrition figures, passed through exactly as the source supplied them. */
export type RecipeNutrition = {
  readonly kcalPer100g?: number
  readonly carbsPercent?: number
  readonly proteinPercent?: number
  readonly fatPercent?: number
  readonly portionWeightG?: number
  readonly portionKcal?: number
}

export type RecipeDetailProps = {
  /** Recipe name — the page's h1. */
  readonly title: string
  /** The chef's short summary, shown in the hero. */
  readonly subtitle?: string
  /** Number of portions the recipe makes. */
  readonly serves?: number
  /** Hero image. Omit for a text-only hero. */
  readonly heroImage?: ContentMediaData
  /** Set when the image was regenerated by AI — shown as a label. */
  readonly imageIsAiEnhanced?: boolean
  /** Marketing intro (markdown). */
  readonly intro?: string
  readonly ingredients?: readonly RecipeIngredient[]
  /** Free-form preparation (markdown). */
  readonly preparation?: string
  /** One entry per method step, in order. */
  readonly methodSteps?: readonly string[]
  /** Chef's notes (markdown). */
  readonly methodNotes?: string
  /** Allergens, verbatim from the source. */
  readonly allergens?: readonly string[]
  readonly nutrition?: RecipeNutrition
  /** Downloadable recipe card. */
  readonly recipePdfUrl?: string
  /**
   * schema.org `Recipe` structured data, built by the registry adapter.
   * Rendered as a JSON-LD script; omit to render none.
   */
  readonly jsonLd?: Readonly<Record<string, unknown>>
  /** Active locale URL prefix (ADR-0015), for markdown links. */
  readonly localeBasePath?: string
  /** How urgently the hero image should load (ADR-0021). */
  readonly loadPriority?: MediaLoadPriority
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/**
 * Serialise structured data for a `<script>` body. `<` is escaped so a value
 * containing `</script>` cannot close the tag early — the standard JSON-LD
 * injection guard.
 */
const serialiseJsonLd = (data: Readonly<Record<string, unknown>>): string =>
  JSON.stringify(data).replace(/</g, '\\u003c')

const round = (n: number): string => String(Math.round(n * 10) / 10)

/** "1 x Each · Code 100234" — whichever halves exist; empty when neither does. */
const ingredientMeta = (ingredient: RecipeIngredient): string =>
  [
    ingredient.portion,
    ingredient.productCode !== undefined && ingredient.productCode !== ''
      ? `Code ${ingredient.productCode}`
      : undefined,
  ]
    .filter((part): part is string => part !== undefined && part !== '')
    .join(' · ')

const factsFor = (
  serves: number | undefined,
  nutrition: RecipeNutrition | undefined,
  allergens: readonly string[],
) => {
  const facts: Attribute[] = []
  if (serves !== undefined) facts.push({ label: 'Serves', value: String(serves) })
  if (nutrition?.portionWeightG !== undefined) {
    facts.push({ label: 'Portion weight', value: `${round(nutrition.portionWeightG)}g` })
  }
  if (nutrition?.portionKcal !== undefined) {
    facts.push({ label: 'Per portion', value: `${round(nutrition.portionKcal)} kcal` })
  }
  if (allergens.length > 0) facts.push({ label: 'Contains', value: allergens.join(', ') })
  return facts
}

const MACROS = [
  { key: 'carbsPercent', label: 'Carbs', className: 'carbs' },
  { key: 'proteinPercent', label: 'Protein', className: 'protein' },
  { key: 'fatPercent', label: 'Fat', className: 'fat' },
] as const

/** Energy split as a stacked bar plus a text legend (the bar alone is not accessible). */
function MacroSplit({ nutrition }: { readonly nutrition: RecipeNutrition }) {
  const parts = MACROS.flatMap((macro) => {
    const value = nutrition[macro.key]
    return value === undefined ? [] : [{ ...macro, value }]
  })
  if (parts.length === 0) return null

  return (
    <div className={styles.macros} data-recipe-macros>
      <div className={styles.macroBar} role="presentation">
        {parts.map((part) => (
          <span
            key={part.key}
            className={clsx(styles.macroSegment, styles[part.className])}
            style={{ flexGrow: part.value }}
          />
        ))}
      </div>
      <ul className={styles.macroLegend}>
        {parts.map((part) => (
          <li key={part.key}>
            <span className={clsx(styles.swatch, styles[part.className])} aria-hidden="true" />
            {part.label} {round(part.value)}%
          </li>
        ))}
      </ul>
    </div>
  )
}

// ---------------------------------------------------------------------------
// Component
// ---------------------------------------------------------------------------

/**
 * RecipeDetail template — the rendered form of a `recipe` content item.
 *
 * Composed from existing parts: a HeroBlock for the title and image, then a
 * contained body of Markdown (intro, preparation, notes),
 * AttributeList (serves, nutrition) and Lists (ingredients, method). Only the
 * layout CSS and the energy-split bar are new.
 *
 * Allergen and nutrition data renders exactly as supplied — nothing here
 * derives, rounds beyond one decimal, or fills in a missing value. Sections
 * with no data are omitted rather than shown empty.
 *
 * Head metadata is the route's job via `recipeMetadataFromSchema`; structured
 * data arrives as the `jsonLd` prop and is emitted inline.
 */
export function RecipeDetail({
  title,
  subtitle,
  serves,
  heroImage,
  imageIsAiEnhanced,
  intro,
  ingredients = [],
  preparation,
  methodSteps = [],
  methodNotes,
  allergens = [],
  nutrition,
  recipePdfUrl,
  jsonLd,
  localeBasePath,
  loadPriority = 'lazy',
}: RecipeDetailProps) {
  const facts = factsFor(serves, nutrition, allergens)
  const markdownProps = localeBasePath !== undefined ? { localeBasePath } : {}
  const hasNutrition =
    nutrition !== undefined && Object.values(nutrition).some((v) => v !== undefined)

  return (
    <article className={clsx('RecipeDetail', styles.root)} data-recipe-detail>
      {jsonLd !== undefined && (
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: serialiseJsonLd(jsonLd) }}
        />
      )}

      <HeroBlock
        {...(heroImage !== undefined && { media: heroImage })}
        loadPriority={loadPriority}
        title={title}
        description={subtitle ?? ''}
        heightBehaviour="fitToContent"
        contentPaddingVertical={120}
        backgroundColor="black"
        overlayColor="black"
        overlayIntensity={100}
        verticalPosition="bottom"
        {...(recipePdfUrl !== undefined && {
          ctas: [
            {
              label: 'Download recipe card (PDF)',
              href: recipePdfUrl,
              variant: 'solid' as const,
              color: 'primary' as const,
            },
          ],
        })}
        {...(localeBasePath !== undefined && { localeBasePath })}
      />

      {(facts.length > 0 || imageIsAiEnhanced === true) && (
        <div className={styles.summary} data-recipe-summary>
          <Container className={clsx(styles.summaryContainer)} gutter>
            {facts.length > 0 && (
              <dl className={styles.facts} data-recipe-facts>
                {facts.map((fact) => (
                  <div key={fact.label} className={styles.fact}>
                    <dt className={styles.factLabel}>{fact.label}</dt>
                    <dd className={styles.factValue}>{fact.value}</dd>
                  </div>
                ))}
              </dl>
            )}
            {imageIsAiEnhanced === true && (
              <span className={styles.aiLabel} data-recipe-ai-image>
                Image enhanced with AI
              </span>
            )}
          </Container>
        </div>
      )}

      <Container gutter>
        <div className={styles.body}>
          {intro !== undefined && intro !== '' && (
            <div className={styles.intro} data-recipe-intro>
              <Markdown content={intro} {...markdownProps} />
            </div>
          )}

          <div className={styles.columns}>
            {ingredients.length > 0 && (
              <section className={styles.ingredients} data-recipe-ingredients>
                <Typography variant="h3" as="h2">
                  Ingredients
                </Typography>
                <List marker="none" gap="sm">
                  {ingredients.map((ingredient, index) => (
                    // Index keys: ingredient names can repeat ("salt") and the
                    // list is a fixed, ordered snapshot of one content item.
                    <ListItem key={index} className={clsx(styles.ingredient)}>
                      <span>
                        {ingredient.quantity !== undefined && ingredient.quantity !== '' && (
                          <strong className={styles.quantity}>{ingredient.quantity} </strong>
                        )}
                        {ingredient.name}
                      </span>
                      {ingredientMeta(ingredient) !== '' && (
                        <span className={styles.ingredientMeta}>{ingredientMeta(ingredient)}</span>
                      )}
                    </ListItem>
                  ))}
                </List>
              </section>
            )}

            {((preparation !== undefined && preparation !== '') ||
              methodSteps.length > 0 ||
              (methodNotes !== undefined && methodNotes !== '')) && (
              <div className={styles.rightColumn}>
                {preparation !== undefined && preparation !== '' && (
                  <section className={styles.preparation} data-recipe-preparation>
                    <Typography variant="h3" as="h2">
                      Preparation
                    </Typography>
                    <Markdown content={preparation} {...markdownProps} />
                  </section>
                )}

                {methodSteps.length > 0 && (
                  <section className={styles.method} data-recipe-method>
                    <Typography variant="h3" as="h2">
                      Method
                    </Typography>
                    <List as="ol" gap="md">
                      {methodSteps.map((step, index) => (
                        <ListItem key={index}>{step}</ListItem>
                      ))}
                    </List>
                  </section>
                )}

                {methodNotes !== undefined && methodNotes !== '' && (
                  <section className={styles.notes} data-recipe-notes>
                    <Typography variant="h4" as="h2">
                      Chef&apos;s notes
                    </Typography>
                    <Markdown content={methodNotes} {...markdownProps} />
                  </section>
                )}
              </div>
            )}

            {hasNutrition && (
              <section className={styles.nutrition} data-recipe-nutrition>
                <Typography variant="h3" as="h2">
                  Nutrition
                </Typography>
                {nutrition.kcalPer100g !== undefined && (
                  <p data-recipe-kcal-per-100g>{`${round(nutrition.kcalPer100g)}kcal/100g`}</p>
                )}
                <MacroSplit nutrition={nutrition} />
              </section>
            )}
          </div>
        </div>
      </Container>
    </article>
  )
}
